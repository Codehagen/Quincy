function rowsOf(pattern: string): number[] {
  return pattern.split(" ").map((row) => {
    let n = 0
    for (let i = 0; i < row.length; i++) {
      if (row[i] === "#") n |= 1 << (4 - i)
    }
    return n
  })
}

const GLYPHS: Record<string, number[]> = Object.fromEntries(
  Object.entries(RAW).map(([ch, pattern]) => [ch, rowsOf(pattern)])
)

/** A hollow box, so an unsupported character is visible as itself missing. */
const BOX = rowsOf("##### #...# #...# #...# #...# #...# #####")

/** Seven row bitmasks, low five bits, high bit on the left. */
export function glyphRows(ch: string): number[] {
  return GLYPHS[ch] ?? BOX
}

export const GLYPH_WIDTH = 5
export const GLYPH_HEIGHT = 7

/** Characters this face actually draws, for the test. */
export function hasGlyph(ch: string): boolean {
  return GLYPHS[ch] != null
}
